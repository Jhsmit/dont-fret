from typing import Any, Iterable, Optional, Type, Union

import numpy as np
import numpy.typing as npt
import polars as pl
from KDEpy import FFTKDE, NaiveKDE
from KDEpy.bw_selection import improved_sheather_jones, scotts_rule, silvermans_rule
from KDEpy.utils import cartesian


def mirror(
    data: np.ndarray,
    mirrors: tuple[Optional[float], Optional[float]],
    tile_data: Optional[Iterable[np.ndarray]] = None,
    sort: bool = True,
) -> np.ndarray | tuple[np.ndarray, list[np.ndarray]]:
    """Mirrors data at specified positions.

    Args:
        data: Data to mirror
        mirrors: Tuple of lower and upper mirror positions. If `None` is specified, no
            mirror is applied.
        tile_data: Optional iterable of data to tile. The data is tiled in the same
            way as the mirrored data.
        sort: If `True`, the data is sorted after mirroring.

    Returns:
        Mirrored data. If `tile_data` is specified, a tuple of mirrored data and
        tiled data is returned. Otherwise, only the mirrored data is returned.
    """

    tile_data = tile_data or []

    for tdata in tile_data:
        if data.shape != tdata.shape:
            raise ValueError("Data and elements of tile_data must have the same shape")

    lower_mirror, upper_mirror = mirrors
    copies = sum(m is not None for m in mirrors)

    data_out = np.empty(shape=data.size * (copies + 1), dtype=data.dtype)
    i0 = data.size if lower_mirror is not None else 0

    data_out[i0 : i0 + data.size] = data

    if lower_mirror is not None:
        data_out[: data.size] = lower_mirror - data
    if upper_mirror is not None:
        data_out[-data.size :] = upper_mirror * 2 - data

    tiled_data = [np.tile(tdata, copies + 1) for tdata in tile_data]

    if sort:
        idx = np.argsort(data_out)
        data_out = data_out[idx]
        tiled_data = [t[idx] for t in tiled_data]

    if tiled_data:
        return data_out, tiled_data

    return data_out


def calculate_kde_2d(
    x: np.ndarray,
    y: np.ndarray,
    bw: Optional[tuple[float, float]] = None,
    kde_class: Type[FFTKDE] | Type[NaiveKDE] | None = None,
    weights: Optional[np.ndarray] = None,
    grid_points: npt.ArrayLike | int | tuple | None = 2**8,
    norm: int = 2,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Calculate KDE on 2D data.

    Args:
        x: 1D array of x-data.
        y: 1D array of y-data.
        bw: x and y direction bandwidths. if None, automatically determined.
        kde_class: Class of KDE to use. If None, automatically determined. Must be a subclass of BaseKDE.
        weights: Optional weights for each data point.
        grid_points: As integer, sets the number of grid points in each dimension. Otherwise,
            see KDEBase.evaluate.
        norm: Norm to use for KDE. Default is 2 (Euclidian).

    Returns:
        grid: Output grid of shape (obs, 2). If a grid is given as `grid_points`, returns this grid,
            otherwise returns the auto generated grid.
        kde_z: KDE values of shape (obs, 2).

    """

    if len(x) != len(y):
        raise ValueError("'x' and 'y' input arrays must have equal length")

    if kde_class is not None:
        pass
    elif len(x) >= 1000:
        kde_class = FFTKDE
    else:
        kde_class = NaiveKDE

    if bw is None:
        bw_x = estimate_bandwidth(x, weights=weights)
        bw_y = estimate_bandwidth(y, weights=weights)
    else:
        bw_x, bw_y = bw
    data = np.stack([x, y]).T
    data_scaled = data / np.array([bw_x, bw_y])

    if isinstance(grid_points, (int, type(None), tuple)):
        # Grid is autogenerated
        grid_eval = grid_points
    else:
        grid_eval = np.array(grid_points)
        # rescale input grid to match scaled data
        grid_eval /= np.array([bw_x, bw_y])

    # grid is points, dimensions
    assert kde_class is not None
    result = (
        kde_class(bw=1, norm=norm).fit(data_scaled, weights=weights).evaluate(grid_eval)  # type: ignore
    )
    if isinstance(result, tuple):
        grid, kde_z = result
    else:
        kde_z = result
        grid = grid_eval

    # rescale grid to match original data
    grid *= np.array([bw_x, bw_y])
    kde_z /= bw_x * bw_y

    return grid, kde_z  # type: ignore


def calculate_kde_1d(
    x: np.ndarray,
    bw: float,
    kde_class: Type[FFTKDE] | Type[NaiveKDE] | None = None,
    weights: Optional[np.ndarray] = None,
    grid_points: npt.ArrayLike | int | tuple | None = 2**8,
    norm: int = 1,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Perform KDE on 1D data.

    Args:
        x: 1D array of data
        bw: Bandwidth.
        kde_class: Class of KDE to use. If None, automatically determined. Must be a subclass of BaseKDE.
        weights: Optional weights for each data point.
        grid_points: As integer, sets the number of grid points in each dimension. Otherwise,
            see KDEBase.evaluate.
        norm: Norm to use for KDE. Default is 1 (Manhattan).

    Returns:
        grid: 1D array of grid points.
        kde_z: 1D array of KDE estimates at grid points.
    """

    if kde_class is not None:
        pass
    elif len(x) >= 1000:
        kde_class = FFTKDE
    else:
        kde_class = NaiveKDE

    data = x.reshape(-1, 1)

    grid, kde_z = (
        FFTKDE(bw=bw, norm=norm).fit(data, weights=weights).evaluate(grid_points)  # type: ignore
    )

    return grid, kde_z


def estimate_bandwidth(
    data: np.ndarray, method: str = "silverman", weights: Union[np.ndarray, None] = None
) -> float:
    """
    Estimate bandwidths for 1d data.

    Args:
        data: 1d array of data.
        method: one of 'silverman', 'scott' or 'ISJ'.
        weights: Optional weights for each data point.

    Returns:
        Estimated bandwidth.

    """

    if method == "silverman":
        bw_func = silvermans_rule
    elif method == "scott":
        bw_func = scotts_rule
    elif method == "ISJ":
        bw_func = improved_sheather_jones
    else:
        raise ValueError(f"Invalid method {method!r}, must be 'silverman', 'scott' or 'ISJ'")

    bw = bw_func(data.reshape(-1, 1), weights=weights)

    return bw


def reshape_grid(grid: np.ndarray, output_shape: tuple[int, int]) -> tuple[np.ndarray, np.ndarray]:
    """Takes an output grid from KDE and reshapes and transposes it to prepare for contour plot"""
    grid_x, grid_y = grid.T
    grid_x = grid_x.reshape(*output_shape)[:, 0]
    grid_y = grid_y.reshape(*output_shape)[0, :]
    return grid_x, grid_y


def remove_limit(data: np.ndarray, lim: tuple[float, float]) -> np.ndarray:
    """Remove data outside of limits.

    Args:
        data: Data to be filtered.
        lim: Limits to filter data.

    Returns:
        Filtered data.

    """
    return data[(data >= lim[0]) & (data <= lim[1])]


def autolimit(
    data: np.ndarray,
    limit: Optional[tuple[Optional[float], Optional[float]]] = None,
    boundary_rel: float = 0.0,
) -> tuple[float, float]:
    """Expands given limit to include all data."""
    limit = limit or (None, None)
    lower_lim = min(data.min(), limit[0] if limit[0] is not None else np.inf)
    upper_lim = max(data.max(), limit[1] if limit[1] is not None else -np.inf)

    if boundary_rel:
        size = upper_lim - lower_lim
        lower_lim -= size * boundary_rel
        upper_lim += size * boundary_rel

    return lower_lim, upper_lim


def make_grid(
    x: np.ndarray,
    y: np.ndarray,
    xlim: Optional[tuple[Optional[float], Optional[float]]] = None,
    ylim: Optional[tuple[Optional[float], Optional[float]]] = None,
    num: Union[tuple[int, int], int] = 2**10,
    boundary_rel: float = 0.05,
):
    """Make a grid of points from given data.

    The limits of the grid are such that all data is included. If additional wider xlim and ylim are given,
    these limits are used instead.

    Args:
        x: x data which the grid should accommodate.
        y: y data which the grid should accommodate.
        xlim: Optional limits for x data.
        ylim: Optional limits for y data.
        num: Number of points in each dimension of the grid. If a tuple is given, the first value is used for x and
            the second for y.
        boundary_rel: Relative size to expand grid limits by.

    Returns:
        A grid of points as a 2D array. The shape is (num[0]*num[1], 2).

    """
    if isinstance(num, int):
        num = (num, num)

    lin_x = np.linspace(*autolimit(x, xlim, boundary_rel), num[0], endpoint=True)
    lin_y = np.linspace(*autolimit(y, ylim, boundary_rel), num[1], endpoint=True)
    return cartesian([lin_x, lin_y])


def kde_2d(
    x: np.ndarray,
    y: np.ndarray,
    mirror_x: Optional[tuple[Optional[float], Optional[float]]] = None,
    weights: Optional[np.ndarray] = None,
    xlim: Optional[tuple[float, float]] = None,
    ylim: Optional[tuple[float, float]] = None,
    num: int = 2**8,
    **kwargs: Any,
):
    """shorthand for mirrorring, weighting and calculating a 2d kde."""

    if mirror_x is not None and weights is not None:
        x, (y, weights) = mirror(x, mirror_x, [y, weights])
    if mirror_x is not None and weights is None:
        x, (y,) = mirror(x, mirror_x, [y])

    grid = make_grid(x, y, xlim, ylim, num=num)
    grid, kde_z = calculate_kde_2d(x, y, weights=weights, grid_points=grid, **kwargs)
    grid_x, grid_y = reshape_grid(grid, (num, num))
    z = kde_z.reshape((num, num)).T

    return grid_x, grid_y, z


def mock_kde(
    y: np.ndarray,
    N: int = 1000,
    bw: Union[tuple[Optional[float], Optional[float]], float, None] = None,
    ylim: Optional[tuple[float, float]] = None,
    num: int = 2**10,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Creates pseudostatic KDE slice"""

    rng = np.random.default_rng()
    if len(y) < N:
        y = rng.choice(y, N, replace=True)

    tdata = np.cumsum(rng.uniform(0, 1, len(y)))
    tdata /= 2 * np.mean(tdata)  # center

    bw_x, bw_y = bw if isinstance(bw, tuple) else (100, bw)
    bw_y = bw_y or estimate_bandwidth(y)
    bw_x = bw_x or 100

    grid = make_grid(tdata, y, xlim=(0, 1), ylim=ylim, num=num)
    grid, kde_z = calculate_kde_2d(tdata, y, bw=(bw_x, bw_y), grid_points=grid)

    grid_x, grid_y = reshape_grid(grid, (num, num))
    z = kde_z.reshape((num, num)).T

    return grid_x, grid_y, z
